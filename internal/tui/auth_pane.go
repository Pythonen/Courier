func (a *authPane) FocusCurrent() tea.Cmd {
	a.blurAll()
	input := a.currentInput()
	if input == nil {
		return nil
	}
	return input.Focus()
}

func (a *authPane) currentInput() *textinput.Model {
	switch a.config.typeID {
	case authBearer:
		return &a.bearer
	case authJWTBearer:
		switch a.cursor {
		case 0:
			return &a.jwtKey
		case 1:
			return &a.jwtPayload
		case 2:
			return &a.jwtHeaders
		case 3:
			return &a.jwtPrefix
		default:
			return &a.jwtQueryName
		}
	case authBasic, authDigest:
		if a.cursor == 0 {
			return &a.username
		}
		return &a.password
	case authAPIKey:
		if a.cursor == 0 {
			return &a.keyName
		}
		return &a.keyValue
	case authOAuth2ClientCredentials, authOAuth2Password, authOAuth2RefreshToken:
		switch a.cursor {
		case 0:
			return &a.oauthTokenURL
		case 1:
			return &a.oauthClientID
		case 2:
			return &a.oauthClientSecret
		case 3:
			return &a.oauthScope
		case 4:
			if a.config.typeID == authOAuth2RefreshToken {
				return &a.oauthRefreshToken
			}
			return &a.username
		default:
			return &a.password
		}
	case authOAuth2AuthorizationCode:
		switch a.cursor {
		case 0:
			return &a.oauthAuthorizationURL
		case 1:
			return &a.oauthTokenURL
		case 2:
			return &a.oauthClientID
		case 3:
			return &a.oauthClientSecret
		case 4:
			return &a.oauthScope
		case 5:
			return &a.oauthCallbackURL
		case 6:
			return &a.oauthAccessToken
		default:
			return &a.oauthRefreshToken
		}
	case authHawk:
		switch a.cursor {
		case 0:
			return &a.hawkID
		case 1:
			return &a.hawkKey
		default:
			return &a.hawkExt
		}
	case authNTLM:
		switch a.cursor {
		case 0:
			return &a.username
		case 1:
			return &a.password
		case 2:
			return &a.ntlmDomain
		default:
			return &a.ntlmWorkstation
		}
	case authOAuth1:
		switch a.cursor {
		case 0:
			return &a.oauth1ConsumerKey
		case 1:
			return &a.oauth1ConsumerSecret
		case 2:
			return &a.oauth1Token
		case 3:
			return &a.oauth1TokenSecret
		case 4:
			return &a.oauth1PrivateKey
		case 5:
			return &a.oauth1Realm
		case 6:
			return &a.oauth1Callback
		default:
			return &a.oauth1Verifier
		}
	case authAWSSignatureV4:
		switch a.cursor {
		case 0:
			return &a.awsAccessKey
		case 1:
			return &a.awsSecretKey
		case 2:
			return &a.awsRegion
		case 3:
			return &a.awsService
		default:
			return &a.awsSessionToken
		}
	default:
		return nil
	}
}

func (a *authPane) UpdateInsert(msg tea.Msg) tea.Cmd {
	input := a.currentInput()
	if input == nil {
		return nil
	}
	var cmd tea.Cmd
	*input, cmd = input.Update(msg)
	return cmd
}

func (a *authPane) UpdateNormal(keyStr string) {
	switch keyStr {
	case "o":
		a.syncConfig()
		a.config.typeID = (a.config.typeID + 1) % authTypeCount
		a.cursor = 0
		a.blurAll()
	case "j":
		if a.cursor < a.fieldCount()-1 {
			a.cursor++
		}
	case "k":
		if a.cursor > 0 {
			a.cursor--
		}
	case " ", "space":
		switch a.config.typeID {
		case authAPIKey:
			a.config.apiKeyLocation = (a.config.apiKeyLocation + 1) % 2
		case authJWTBearer:
			a.config.jwtLocation = (a.config.jwtLocation + 1) % 2
		case authOAuth1:
			a.config.oauth1Location = (a.config.oauth1Location + 1) % 2
		}
	case "h", "left":
		switch a.config.typeID {
		case authJWTBearer:
			a.cycleJWTAlgorithm(-1)
		case authHawk:
			a.cycleHawkAlgorithm()
		case authOAuth1:
			a.cycleOAuth1Signature(-1)
		}
	case "l", "right":
		switch a.config.typeID {
		case authJWTBearer:
			a.cycleJWTAlgorithm(1)
		case authHawk:
			a.cycleHawkAlgorithm()
		case authOAuth1:
			a.cycleOAuth1Signature(1)
		}
	case "b":
		if a.config.typeID == authJWTBearer && strings.HasPrefix(a.config.jwtAlgorithm, "HS") {
			a.config.jwtSecretBase64 = !a.config.jwtSecretBase64
		} else if a.config.typeID == authOAuth1 {
			a.config.oauth1IncludeBodyHash = !a.config.oauth1IncludeBodyHash
		}
	case "p":
		if a.config.typeID == authOAuth2AuthorizationCode {
			a.config.oauthPKCE = !a.config.oauthPKCE
		}
	case "v":
		a.setSecretsVisible(!a.secretsVisible)
	case "a":
		if a.config.typeID == authOAuth2AuthorizationCode {
			styles := []string{"basic", "body", "none"}
			index := 0
			for candidate, style := range styles {
				if style == a.config.oauthClientAuth {
					index = candidate
					break
				}
			}
			a.config.oauthClientAuth = styles[(index+1)%len(styles)]
		}
	}
}

func (a *authPane) cycleHawkAlgorithm() {
	if a.config.hawkAlgorithm == "sha1" {
		a.config.hawkAlgorithm = "sha256"
	} else {
		a.config.hawkAlgorithm = "sha1"
	}
}

func (a *authPane) cycleOAuth1Signature(direction int) {
	methods := []string{"HMAC-SHA1", "HMAC-SHA256", "RSA-SHA1", "PLAINTEXT"}
	index := 0
	for candidate, method := range methods {
		if method == a.config.oauth1SignatureMethod {
			index = candidate
			break
		}
	}
	a.config.oauth1SignatureMethod = methods[(index+direction+len(methods))%len(methods)]
}

func (a *authPane) cycleJWTAlgorithm(direction int) {
	index := 0
	for candidate, algorithm := range jwtAlgorithms {
		if algorithm == a.config.jwtAlgorithm {
			index = candidate
			break
		}
	}
	index = (index + direction + len(jwtAlgorithms)) % len(jwtAlgorithms)
	a.config.jwtAlgorithm = jwtAlgorithms[index]
}

func (a *authPane) SetWidth(width int) {
	a.width = width
	inputWidth := width - 14
	if inputWidth < 10 {
		inputWidth = 10
	}
	for _, input := range []*textinput.Model{&a.bearer, &a.jwtKey, &a.jwtPayload, &a.jwtHeaders, &a.jwtPrefix, &a.jwtQueryName, &a.username, &a.password, &a.keyName, &a.keyValue, &a.oauthAuthorizationURL, &a.oauthTokenURL, &a.oauthClientID, &a.oauthClientSecret, &a.oauthScope, &a.oauthCallbackURL, &a.oauthAccessToken, &a.oauthRefreshToken, &a.hawkID, &a.hawkKey, &a.hawkExt, &a.ntlmDomain, &a.ntlmWorkstation, &a.oauth1ConsumerKey, &a.oauth1ConsumerSecret, &a.oauth1Token, &a.oauth1TokenSecret, &a.oauth1PrivateKey, &a.oauth1Realm, &a.oauth1Callback, &a.oauth1Verifier, &a.awsAccessKey, &a.awsSecretKey, &a.awsRegion, &a.awsService, &a.awsSessionToken} {
		input.SetWidth(inputWidth)
	}
	awsLocationWidth := max(8, (inputWidth-12)/2)
	a.awsRegion.SetWidth(awsLocationWidth)
	a.awsService.SetWidth(awsLocationWidth)
}

