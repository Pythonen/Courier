func (c authConfig) applyHeaders(req *http.Request) {
	switch c.typeID {
	case authBearer:
		if token := strings.TrimSpace(c.bearerToken); token != "" {
			req.Header.Set("Authorization", "Bearer "+token)
		}
	case authBasic:
		req.SetBasicAuth(c.username, c.password)
	case authAPIKey:
		if c.apiKeyLocation == apiKeyHeader && strings.TrimSpace(c.apiKeyName) != "" {
			req.Header.Set(strings.TrimSpace(c.apiKeyName), c.apiKeyValue)
		}
	case authOAuth2AuthorizationCode:
		if token := strings.TrimSpace(c.oauthAccessToken); token != "" {
			tokenType := strings.TrimSpace(c.oauthTokenType)
			if tokenType == "" {
				tokenType = "Bearer"
			}
			req.Header.Set("Authorization", tokenType+" "+token)
		}
	}
}
