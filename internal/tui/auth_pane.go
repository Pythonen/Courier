func (a *authPane) setSecretsVisible(visible bool) {
	a.secretsVisible = visible
	mode := textinput.EchoPassword
	if visible {
		mode = textinput.EchoNormal
	}
	for _, input := range a.secretInputs() {
		input.EchoMode = mode
	}
}

